#!/usr/bin/env python3
# Generates firmware/ESP32S3_K197/hold_shape.h: the "HOLD" and "AUTO" indicators
# (v24 DATA HOLD) drawn on the LCD replica in place of STO and RCL - the same
# font and letter height as the original indicator artwork (and TAG, SD!), but
# squeezed horizontally to KEITHLEY_HOLD_W pixels so that the four letters fit
# left of the AC symbol (at the normal width "HOLD" would be 46 px). Both
# words get the same width, so they read as one pair.
#
# The original artwork (REM, REL, BAT, STO, RCL) matches DejaVu Sans Condensed
# Bold best (see gen_tag_shape.py); the scale is fitted to "REM" (its ink box
# is exactly 35 x 13 pixels), rendered supersampled 16x and box-filtered to
# coverage 0..255.
#
# Usage: python3 tools/gen_hold_shape.py [out.h]   (needs Pillow, the DejaVu fonts)
import sys
from PIL import Image, ImageDraw, ImageFont

FONT = '/usr/share/fonts/truetype/dejavu/DejaVuSansCondensed-Bold.ttf'
BIG = 200
SS = 16
TRACK = -0.01  # letter spacing (fraction of the font size) of the best fit
WIDTH = 35     # both words squeezed to this width (pixels)

font = ImageFont.truetype(FONT, BIG)


def big(text):
    img = Image.new('L', (2400, 400), 0)
    draw = ImageDraw.Draw(img)
    x = 10
    for ch in text:
        draw.text((x, 50), ch, font=font, fill=255)
        x += font.getlength(ch) + TRACK * BIG
    return img


rem = big('REM').getbbox()
h = 13
out = sys.argv[1] if len(sys.argv) > 1 else 'hold_shape.h'
with open(out, 'w') as f:
    f.write('// hold_shape.h - GENERATED by tools/gen_hold_shape.py, do not edit by hand.\n')
    f.write('// v24: the "HOLD" and "AUTO" indicators (DATA HOLD) shown in place of STO and RCL on the\n')
    f.write('// LCD replica, coverage 0..255, row by row, in the style of keithley_shapes.h.\n\n')
    f.write('#ifndef HOLD_SHAPE_H\n#define HOLD_SHAPE_H\n\n#include <Arduino.h>\n\n')
    f.write('#define KEITHLEY_HOLD_W %d\n#define KEITHLEY_HOLD_H %d\n\n' % (WIDTH, h))
    for name, text in (('hold', 'HOLD'), ('auto', 'AUTO')):
        img = big(text)
        box = img.getbbox()
        img = img.crop((box[0], rem[1], box[2], rem[3]))
        small = img.resize((WIDTH * SS, h * SS), Image.LANCZOS).resize((WIDTH, h), Image.BOX)
        data = list(small.tobytes())
        f.write('const uint8_t keithley_%s_mask[%d] PROGMEM = {\n' % (name, len(data)))
        for i in range(0, len(data), 32):
            f.write(','.join(str(v) for v in data[i:i + 32]) + ',\n')
        f.write('};\n\n')
    f.write('#endif // HOLD_SHAPE_H\n')
print('%s: 2 x %d x %d' % (out, WIDTH, h))
