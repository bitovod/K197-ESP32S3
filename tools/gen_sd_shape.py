#!/usr/bin/env python3
# Generates firmware/ESP32S3_K197/sd_shape.h (unchanged since): the "SD!" indicator (v23 SD card
# problem) drawn on the LCD replica in place of BAT - same font, size and
# antialiasing as the original indicator artwork and as TAG (gen_tag_shape.py).
#
# The original artwork (REM, REL, BAT, STO, RCL) matches DejaVu Sans Condensed
# Bold best of the fonts tried (mean squared error over the five words); the
# scale is fitted to "REM": its ink box is exactly 35 x 13 pixels. "SD!" is
# rendered with the same scale and letter spacing, top and bottom aligned with
# REM's cap height, supersampled 16x and box-filtered to coverage 0..255.
#
# Usage: python3 tools/gen_sd_shape.py [out.h]   (needs Pillow, the DejaVu fonts)
import sys
from PIL import Image, ImageDraw, ImageFont

FONT = '/usr/share/fonts/truetype/dejavu/DejaVuSansCondensed-Bold.ttf'
BIG = 200
SS = 16
TRACK = -0.01  # letter spacing (fraction of the font size) of the best fit
TEXT = 'SD!'

font = ImageFont.truetype(FONT, BIG)


def big(text):
    img = Image.new('L', (2400, 400), 0)
    draw = ImageDraw.Draw(img)
    x = 10
    for ch in text:
        draw.text((x, 50), ch, font=font, fill=255)
        x += font.getlength(ch) + TRACK * BIG
    return img


rem = big('REM').getbbox()
sx = 35.0 / (rem[2] - rem[0])
img = big(TEXT)
box = img.getbbox()
img = img.crop((box[0], rem[1], box[2], rem[3]))
w = max(1, round((box[2] - box[0]) * sx))
h = 13
small = img.resize((w * SS, h * SS), Image.LANCZOS).resize((w, h), Image.BOX)
data = list(small.tobytes())

out = sys.argv[1] if len(sys.argv) > 1 else 'sd_shape.h'
with open(out, 'w') as f:
    f.write('// sd_shape.h - GENERATED by tools/gen_sd_shape.py, do not edit by hand.\n')
    f.write('// v23: the "SD!" indicator (SD card problem) shown in place of BAT on the LCD replica,\n')
    f.write('// coverage 0..255, row by row, in the style of keithley_shapes.h.\n\n')
    f.write('#ifndef SD_SHAPE_H\n#define SD_SHAPE_H\n\n#include <Arduino.h>\n\n')
    f.write('#define KEITHLEY_SD_W %d\n#define KEITHLEY_SD_H %d\n\n' % (w, h))
    f.write('const uint8_t keithley_sd_mask[%d] PROGMEM = {\n' % len(data))
    for i in range(0, len(data), 32):
        f.write(','.join(str(v) for v in data[i:i + 32]) + ',\n')
    f.write('};\n\n#endif // SD_SHAPE_H\n')
print('%s: %d x %d' % (out, w, h))
