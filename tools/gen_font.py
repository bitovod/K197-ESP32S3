#!/usr/bin/env python3
# gen_font.py - generates font_data.h (antialiased monospaced bitmap fonts) for the
# ESP32S3_K197 sketch. Needs Pillow, fontTools and the font files named below.
#
# Usage: python3 gen_font.py [--font PRESET] [--out font_data.h] [--list]
#
# A PRESET names one monospaced font file (plus an optional fallback file that
# supplies glyphs the main font lacks, e.g. the capital omega) - see PRESETS below.
# The roles (sizes) are given as the wanted HEIGHT OF THE DIGITS in pixels, the
# script finds the matching pixel size for whichever font is used, so switching the
# font keeps the picture's proportions:
#
#   FONT_STAT   numbers and units of the four statistics (largest text)
#   FONT_STAT2  smaller fallback for an unusually long statistic
#   FONT_STAT3  smallest fallback
#   FONT_LIVE   live value and its unit (top right)
#   FONT_LEGEND the legends (AVG, MED, MAX, MIN)
#   FONT_TINY   date and time on the top edge (digits 12 px: the font's hinting has no 11 px size)
#
# Every glyph is stored as a full cell (cellW x cellH, 8-bit coverage, 0-255),
# exactly like the artwork masks in keithley_shapes.h, so the framebuffer code can
# draw text with the same palette ramps as the indicators. Glyph index:
# ASCII 32..126 -> 0..94, micro sign -> 95, capital omega -> 96.
#
# Licenses: DejaVu = Bitstream Vera license + public domain additions; JetBrains Mono,
# IBM Plex Mono, Red Hat Mono, Geist Mono = SIL Open Font License 1.1. Both allow
# embedding the rendered glyphs in firmware; keep the license texts with the project
# if it is ever published.

import argparse
import sys
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.pens.recordingPen import DecomposingRecordingPen
import tempfile, os

C = '/mnt/skills/examples/canvas-design/canvas-fonts/'
D = '/usr/share/fonts/truetype/'

PRESETS = {
    'dejavu':   dict(file=D + 'dejavu/DejaVuSansMono-Bold.ttf', fallback=None),
    # plain_zero: JetBrains Mono's zero has a dot inside, which on a small display seen from a distance is
    # easy to take for an 8; the dot contour is removed from the glyph (the rest of the font is untouched).
    'jetbrains': dict(file=C + 'JetBrainsMono-Bold.ttf', fallback=None, plain_zero=True),
    'plex':     dict(file=C + 'IBMPlexMono-Bold.ttf', fallback=D + 'dejavu/DejaVuSansMono-Bold.ttf'),
    'redhat':   dict(file=C + 'RedHatMono-Bold.ttf', fallback=D + 'dejavu/DejaVuSansMono-Bold.ttf'),
    'geist':    dict(file=C + 'GeistMono-Bold.ttf', fallback=None),
}

# role -> wanted digit height in pixels
ROLES = [
    ('STAT',  20),
    ('STAT2', 17),
    ('STAT3', 14),
    ('LIVE',  16),
    ('LEGEND', 14),
    ('TINY',  12),
]

CODES = [chr(c) for c in range(32, 127)] + ['\u00b5', '\u03a9']


def size_for_digit_height(path, target):
    for size in range(8, 80):
        f = ImageFont.truetype(path, size)
        top = -f.getbbox('8', anchor='ls')[1]
        if top >= target:
            return size
    raise SystemExit('no size found for ' + path)


def has_glyph(path, ch):
    return ord(ch) in TTFont(path, fontNumber=0)['cmap'].getBestCmap()


def plain_zero_font(path):
    """Returns the path of a copy of the font whose zero has no dot/slash, or the original path if the
    glyph does not look as expected (outer outline + inner counter + dot = 3 contours)."""
    f = TTFont(path)
    glyph_set = f.getGlyphSet()
    rec = DecomposingRecordingPen(glyph_set)
    glyph_set['zero'].draw(rec)
    contours, cur = [], []
    for op, args in rec.value:
        cur.append((op, args))
        if op in ('closePath', 'endPath'):
            contours.append(cur)
            cur = []
    if len(contours) != 3:
        print('warning: the zero glyph has %d contours, not 3 - left as it is' % len(contours), file=sys.stderr)
        return path
    pen = TTGlyphPen(None)
    for contour in contours[:2]:
        for op, args in contour:
            getattr(pen, op)(*args)
    f['glyf']['zero'] = pen.glyph()
    handle, tmp = tempfile.mkstemp(suffix='.ttf')
    os.close(handle)
    f.save(tmp)
    return tmp


def build(preset_name, out_path):
    preset = PRESETS[preset_name]
    main_path, fb_path = preset['file'], preset['fallback']
    render_path = plain_zero_font(main_path) if preset.get('plain_zero') else main_path
    lines = []
    lines.append('// font_data.h')
    lines.append('// GENERATED by tools/gen_font.py (preset "%s") - do not edit by hand,' % preset_name)
    lines.append('// change the script (font, digit heights, glyph set) and run it again.')
    lines.append('//')
    lines.append('// Monospaced, antialiased bitmap fonts. Every glyph is a full cell of')
    lines.append('// cellW x cellH pixels, 8-bit coverage (0-255, same convention as the masks in')
    lines.append('// keithley_shapes.h), drawn by fbDrawText() in framebuffer.h through the same')
    lines.append('// palette ramps as the indicator words. `ascent` is the distance from the top')
    lines.append('// of the cell to the baseline; `advance` is the horizontal pitch (equal to')
    lines.append('// cellW - glyphs are left aligned in their cell); `digitHeight` is the height of')
    lines.append('// the digits above the baseline in pixels.')
    lines.append('//')
    lines.append('// Glyph index: ASCII 32..126 -> 0..94, FONT_CH_MICRO -> 95, FONT_CH_OHM -> 96;')
    lines.append('// any other character is drawn as a space. Use the two special characters')
    lines.append('// by character code, never inside a string literal escape that could swallow')
    lines.append('// the following character (build "uA" with snprintf("%c%s", FONT_CH_MICRO, "A")).')
    lines.append('//')
    lines.append('// Font: %s' % main_path.split('/')[-1] + (', zero without the dot' if preset.get('plain_zero') else '') + (' (+ %s for missing glyphs)' % fb_path.split('/')[-1] if fb_path else ''))
    lines.append('// Licenses: see tools/gen_font.py.')
    lines.append('')
    lines.append('#ifndef FONT_DATA_H')
    lines.append('#define FONT_DATA_H')
    lines.append('')
    lines.append('#include <Arduino.h>')
    lines.append('')
    lines.append('#define FONT_GLYPH_COUNT %d' % len(CODES))
    lines.append("#define FONT_CH_MICRO '\\001'")
    lines.append("#define FONT_CH_OHM   '\\002'")
    lines.append('')
    lines.append('struct FontDef')
    lines.append('{')
    lines.append('    const uint8_t *cells;')
    lines.append('    uint8_t cellW;')
    lines.append('    uint8_t cellH;')
    lines.append('    uint8_t ascent;')
    lines.append('    uint8_t advance;')
    lines.append('    uint8_t digitHeight;')
    lines.append('};')
    lines.append('')
    report = []
    for role, digit_h in ROLES:
        size = size_for_digit_height(render_path, digit_h)
        font = ImageFont.truetype(render_path, size)
        fb_font = ImageFont.truetype(fb_path, size_for_digit_height(fb_path, digit_h)) if fb_path else None
        ascent, descent = font.getmetrics()
        cell_w = int(round(font.getlength('0')))
        cell_h = ascent + descent
        data = []
        for ch in CODES:
            use = font
            if not has_glyph(main_path, ch):
                if fb_font is None:
                    raise SystemExit('font lacks U+%04X and no fallback is set' % ord(ch))
                use = fb_font
            img = Image.new('L', (cell_w, cell_h), 0)
            ImageDraw.Draw(img).text((0, ascent), ch, fill=255, font=use, anchor='ls')
            data.extend(img.tobytes())
        lines.append('// %s: %d px, digits %d px high, cell %dx%d, ascent %d' % (role, size, digit_h, cell_w, cell_h, ascent))
        lines.append('static const uint8_t font_%s_cells[%d] PROGMEM = {' % (role.lower(), len(data)))
        row = []
        for v in data:
            row.append(str(v))
            if len(row) == 32:
                lines.append(','.join(row) + ',')
                row = []
        if row:
            lines.append(','.join(row) + ',')
        lines.append('};')
        lines.append('static const FontDef FONT_%s = {font_%s_cells, %d, %d, %d, %d, %d};' % (role, role.lower(), cell_w, cell_h, ascent, cell_w, digit_h))
        lines.append('')
        report.append((role, size, digit_h, cell_w, cell_h, ascent))
    lines.append('#endif // FONT_DATA_H')
    open(out_path, 'w').write('\n'.join(lines) + '\n')
    return report


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--font', default='jetbrains', choices=sorted(PRESETS))
    ap.add_argument('--out', default='font_data.h')
    args = ap.parse_args()
    for r in build(args.font, args.out):
        print('%-6s px %2d  digits %2d  cell %2dx%2d  ascent %2d' % r)
    print('wrote', args.out)
