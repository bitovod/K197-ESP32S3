#!/usr/bin/env python3
# gen_pixel_font.py - generates font_pixel.h (the 5x7 one-bit pixel font of the graph screen, v14)
# for the ESP32S3_K197 sketch from the "classic" 5x7 font of the Adafruit GFX library.
#
# Usage: python3 gen_pixel_font.py PATH/TO/Adafruit-GFX-Library/glcdfont.c [--out font_pixel.h]
#
# glcdfont.c holds 256 glyphs (code page 437) of 5 columns each, one byte per column, bit 0 = top
# row, 7 rows used. Kept from it: ASCII 32..126, the micro sign (CP437 0xE6) and the capital omega
# (CP437 0xEA) - the same 97 glyphs, in the same order, as the antialiased fonts in font_data.h, so
# the same text (FONT_CH_MICRO/FONT_CH_OHM included) can be drawn with either.
# Changed on purpose: the zero has no slash (a slashed or dotted zero reads as an 8 on the small
# display - the same reason as the plain zero of font_data.h).
#
# License of the glyph data: Adafruit GFX Library, BSD license, Copyright (c) 2012 Adafruit
# Industries (license.txt of the library) - keep that notice with the project if it is published.

import argparse
import re

PLAIN_ZERO = [0x3E, 0x41, 0x41, 0x41, 0x3E]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('glcdfont')
    ap.add_argument('--out', default='font_pixel.h')
    a = ap.parse_args()
    text = open(a.glcdfont).read()
    body = text[text.index('font[]'):]
    body = body[body.index('{') + 1:body.index('};')]
    data = [int(x, 16) for x in re.findall(r'0x[0-9A-Fa-f]{2}', body)]
    if len(data) < 256 * 5:
        raise SystemExit('unexpected glcdfont.c content (%d bytes)' % len(data))
    codes = list(range(32, 127)) + [0xE6, 0xEA]
    lines = []
    lines.append('// font_pixel.h')
    lines.append('// GENERATED by tools/gen_pixel_font.py from glcdfont.c of the Adafruit GFX library - do not edit by')
    lines.append('// hand, change the script and run it again.')
    lines.append('//')
    lines.append('// v14: the one-bit 5x7 pixel font of the graph screen (axis labels, header line). 97 glyphs in the')
    lines.append('// same order as font_data.h: ASCII 32..126 -> 0..94, FONT_CH_MICRO -> 95, FONT_CH_OHM -> 96. Each')
    lines.append('// glyph is 5 bytes, one per column (left to right), bit 0 = top row, rows 0..6 used; drawn with an')
    lines.append('// advance of FB_PIXEL_FONT_ADVANCE (6) pixels by fbDrawPixelText() in framebuffer.h. The zero is')
    lines.append('// drawn without the slash of the original font.')
    lines.append('//')
    lines.append('// Glyph data: Adafruit GFX Library, BSD license, Copyright (c) 2012 Adafruit Industries.')
    lines.append('')
    lines.append('#ifndef FONT_PIXEL_H')
    lines.append('#define FONT_PIXEL_H')
    lines.append('')
    lines.append('#include <Arduino.h>')
    lines.append('')
    lines.append('#define FONT_PIXEL_GLYPH_COUNT %d' % len(codes))
    lines.append('#define FONT_PIXEL_GLYPH_BYTES 5')
    lines.append('')
    lines.append('static const uint8_t font_pixel_5x7[FONT_PIXEL_GLYPH_COUNT * FONT_PIXEL_GLYPH_BYTES] PROGMEM = {')
    for c in codes:
        cols = data[c * 5:c * 5 + 5]
        if c == ord('0'):
            cols = PLAIN_ZERO
        name = chr(c) if 32 < c < 127 else {32: 'space', 0xE6: 'micro', 0xEA: 'omega'}[c]
        if name == '\\':
            name = 'backslash'
        lines.append('    %s, // %s' % (', '.join('0x%02X' % b for b in cols), name))
    lines.append('};')
    lines.append('')
    lines.append('#endif // FONT_PIXEL_H')
    open(a.out, 'w').write('\n'.join(lines) + '\n')
    print('wrote', a.out, len(codes), 'glyphs')


if __name__ == '__main__':
    main()
